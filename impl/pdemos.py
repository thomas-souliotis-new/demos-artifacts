"""Reference prototype of P-DEMOS (positional-scoring extension of DEMOS-1).

Group: NIST P-256 (via pycryptodome), written additively. Commitments are
lifted ElGamal Com(v; r) = (rG, vG + rH), which is perfectly binding and
additively homomorphic.

This is a proof-of-concept for correctness and cost measurement. It does not
implement DEMOS' challenge amplification or randomness extractor: the verifier
challenge is derived directly from the voters' coins.
"""

import secrets
import time

from Crypto.PublicKey import ECC

Q = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551  # P-256 order
G = ECC.construct(curve="p256", d=1).pointQ
O = ECC.EccPoint(0, 0, curve="p256")  # point at infinity


def rand_q():
    return 1 + secrets.randbelow(Q - 1)


def smul(pt, k):
    k %= Q
    return O if k == 0 else pt * k


class Ck:
    """Commitment key. H may be generated by the (untrusted) EA: binding is perfect."""

    def __init__(self):
        self.h = smul(G, rand_q())

    def com(self, v, r):
        return (smul(G, r), smul(G, v) + smul(self.h, r))

    def check(self, c, v, r):
        return c == self.com(v, r)


def cmul(a, b):
    """Homomorphic combination (written multiplicatively in the paper)."""
    return (a[0] + b[0], a[1] + b[1])


def cpow(a, w):
    return (smul(a[0], w), smul(a[1], w))


ONE = (O, O)


# ---------------------------------------------------------------- OR proof
# Statement: c = Com(v; r) with v in {s_0..s_{k-1}}. For each branch i this is
# a Chaum-Pedersen equality-of-logs: log_g c1 = log_h (c2 / g^{s_i}).
# CDS composition: branch challenges sum to the global challenge e (mod Q).


def or_first(ck, c, values, true_idx, r):
    k = len(values)
    st = {"w": rand_q(), "e": [0] * k, "z": [0] * k, "i": true_idx, "r": r}
    a = [None] * k
    for i, s in enumerate(values):
        if i == true_idx:
            a[i] = (smul(G, st["w"]), smul(ck.h, st["w"]))
        else:
            ei, zi = rand_q(), rand_q()
            st["e"][i], st["z"][i] = ei, zi
            y2 = c[1] + smul(G, Q - s)
            a[i] = (smul(G, zi) + smul(c[0], Q - ei), smul(ck.h, zi) + smul(y2, Q - ei))
    return a, st


def or_third(st, e):
    i = st["i"]
    es = list(st["e"])
    es[i] = (e - sum(es) + es[i]) % Q
    zs = list(st["z"])
    zs[i] = (st["w"] + es[i] * st["r"]) % Q
    return es, zs


def or_verify(ck, c, values, a, e, es, zs):
    if sum(es) % Q != e % Q:
        return False
    for s, (a1, a2), ei, zi in zip(values, a, es, zs):
        y2 = c[1] + smul(G, Q - s)
        if smul(G, zi) != a1 + smul(c[0], ei):
            return False
        if smul(ck.h, zi) != a2 + smul(y2, ei):
            return False
    return True


# ---------------------------------------------------------------- protocol


class Election:
    def __init__(self, n, m, weights=None, score_mode=False):
        self.n, self.m = n, m
        self.w = weights or [m - 1 - i for i in range(m)]  # Borda by default
        self.score_mode = score_mode
        W = max(self.w) if score_mode else 1
        self.x = max(n * W, m) + 1
        assert self.x**m <= Q, "x^m must not exceed the group order"
        self.X = [self.x**j for j in range(m)]
        self.S = sum(self.X)
        self.ck = Ck()

    # Setup: EA creates ballots and the bulletin board (BB).
    def setup(self, cheat_ballots=()):
        self.bb, self.sec, self.paper = [], [], []
        for l in range(self.n):
            parts_bb, parts_sec, parts_paper = [], [], []
            for a in (0, 1):
                m = self.m
                pi = list(range(m))
                secrets.SystemRandom().shuffle(pi)
                codes = set()
                while len(codes) < m:  # vote codes within a part must be distinct
                    codes.add(secrets.randbits(64))
                codes = list(codes)
                # value placed under candidate j's code (honest: x^j)
                enc = list(range(m))
                if l in cheat_ballots and a == 0:
                    enc[0], enc[1] = enc[1], enc[0]  # mapping attack on part 0
                U, E, a1, st = [None] * m, [None] * m, [None] * m, [None] * m
                t, r = [None] * m, [None] * m
                for j in range(m):
                    p = pi[j]
                    t[p], r[p] = rand_q(), rand_q()
                    U[p] = self.ck.com(codes[j], t[p])
                    E[p] = self.ck.com(self.X[enc[j]], r[p])
                    a1[p], st[p] = or_first(self.ck, E[p], self.X, enc[j], r[p])
                parts_bb.append({"U": U, "E": E, "a": a1, "R": sum(r) % Q})
                parts_sec.append({"pi": pi, "codes": codes, "enc": enc, "t": t, "r": r, "st": st})
                parts_paper.append({cand: codes[cand] for cand in range(m)})
            self.bb.append({"tag": l, "parts": parts_bb})
            self.sec.append(parts_sec)
            self.paper.append(parts_paper)

    # Cast: voter picks a part with a coin and submits codes in rank order.
    def cast(self, l, ranking, a):
        return {"tag": l, "a": a, "codes": [self.paper[l][a][c] for c in ranking]}

    def tally(self, votes):
        coins = "".join(str(v["a"]) for v in votes)
        e = int(coins, 2) % Q if coins else 0  # stand-in for DEMOS' extractor
        self.e = e
        pos_tallies = [[] for _ in range(self.m)]
        for v in votes:
            l, a = v["tag"], v["a"]
            s, part = self.sec[l][a], self.bb[l]["parts"][a]
            code_pos = {s["codes"][j]: s["pi"][j] for j in range(self.m)}
            part["cast"] = []
            for i, code in enumerate(v["codes"]):
                p = code_pos[code]
                part["cast"].append((code, p, s["t"][p]))  # open U_p
                pos_tallies[i].append(part["E"][p])
            part["resp"] = [or_third(s["st"][p], e) for p in range(self.m)]
            # open the audit part position by position: (code, value, randomness)
            aud = self.sec[l][1 - a]
            opened = [None] * self.m
            for j in range(self.m):
                p = aud["pi"][j]
                opened[p] = {"code": aud["codes"][j], "value": self.X[aud["enc"][j]],
                             "t": aud["t"][p], "r": aud["r"][p]}
            self.bb[l]["parts"][1 - a]["open"] = opened
        self.votes = votes
        # open aggregated commitments
        if self.score_mode:
            agg = ONE
            for i in range(self.m):
                for c in pos_tallies[i]:
                    agg = cmul(agg, cpow(c, self.w[i])) if self.w[i] else agg
            self.result_commit = [agg]
            self.result_open = [self._open_score(votes)]
        else:
            self.result_commit, self.result_open = [], []
            for i in range(self.m):
                agg = ONE
                for c in pos_tallies[i]:
                    agg = cmul(agg, c)
                self.result_commit.append(agg)
                self.result_open.append(self._open_position(votes, i))

    def _open_position(self, votes, i):
        V = R = 0
        for v in votes:
            s = self.sec[v["tag"]][v["a"]]
            code_pos = {s["codes"][j]: s["pi"][j] for j in range(self.m)}
            p = code_pos[v["codes"][i]]
            j = s["pi"].index(p)
            V += self.X[s["enc"][j]]
            R += s["r"][p]
        return V, R % Q

    def _open_score(self, votes):
        V = R = 0
        for i in range(self.m):
            Vi, Ri = self._open_position(votes, i)
            V += self.w[i] * Vi
            R += self.w[i] * Ri
        return V, R % Q

    def decode(self):
        out = []
        for V, _ in self.result_open:
            out.append([(V // self.x**j) % self.x for j in range(self.m)])
        return out  # matrix mode: out[i][j] = #times candidate j ranked i; score mode: [scores]

    # Verify: anyone, using only the BB (and, for individual checks, the paper ballot).
    def verify_universal(self):
        e = int("".join(str(v["a"]) for v in self.votes), 2) % Q
        pos_tallies = [[] for _ in range(self.m)]
        tags = [v["tag"] for v in self.votes]
        if len(set(tags)) != len(tags) or len({b["tag"] for b in self.bb}) != len(self.bb):
            return False, "U1: duplicate tag or ballot cast twice"
        for v in self.votes:
            l, a = v["tag"], v["a"]
            part = self.bb[l]["parts"][a]
            # permutation check (both parts)
            for pp in self.bb[l]["parts"]:
                prod = ONE
                for c in pp["E"]:
                    prod = cmul(prod, c)
                if not self.ck.check(prod, self.S, pp["R"]):
                    return False, f"ballot {l}: permutation check"
            for i, (code, p, t) in enumerate(part["cast"]):
                if code != v["codes"][i] or not self.ck.check(part["U"][p], code, t):
                    return False, f"ballot {l}: code opening"
                pos_tallies[i].append(part["E"][p])
            if len({p for _, p, _ in part["cast"]}) != self.m:
                return False, f"ballot {l}: repeated position"
            for p in range(self.m):
                es, zs = part["resp"][p]
                if not or_verify(self.ck, part["E"][p], self.X, part["a"][p], e, es, zs):
                    return False, f"ballot {l}: OR proof"
            ap = self.bb[l]["parts"][1 - a]
            for p, o in enumerate(ap["open"]):
                if not self.ck.check(ap["U"][p], o["code"], o["t"]):
                    return False, f"ballot {l}: audit code"
                if o["value"] not in self.X or not self.ck.check(ap["E"][p], o["value"], o["r"]):
                    return False, f"ballot {l}: audit value"
            if len({o["code"] for o in ap["open"]}) != self.m:
                return False, f"ballot {l}: U3 repeated audit code"
        if self.score_mode:
            agg = ONE
            for i in range(self.m):
                for c in pos_tallies[i]:
                    agg = cmul(agg, cpow(c, self.w[i])) if self.w[i] else agg
            commits = [agg]
        else:
            commits = []
            for i in range(self.m):
                agg = ONE
                for c in pos_tallies[i]:
                    agg = cmul(agg, c)
                commits.append(agg)
        for c, (V, R) in zip(commits, self.result_open):
            if not 0 <= V < self.x**self.m or not self.ck.check(c, V, R):
                return False, "tally opening"
        return True, "ok"

    def voter_check(self, l, a, submitted=None):
        """Individual checks (I1)-(I2) of voter l, who cast part a.

        (I1): for each candidate, the code printed next to it on the audit part
        opens at a position whose E-commitment opens to that candidate's value.
        (I2): the vote recorded on the BB equals the one she submitted.
        """
        by_code = {o["code"]: o["value"] for o in self.bb[l]["parts"][1 - a]["open"]}
        paper = self.paper[l][1 - a]
        if any(by_code.get(paper[cand]) != self.X[cand] for cand in range(self.m)):
            return False
        if submitted is not None:
            recorded = next((v for v in self.votes if v["tag"] == l), None)
            if recorded != submitted:
                return False
        return True


def borda_from_matrix(mat, w):
    m = len(mat)
    return [sum(w[i] * mat[i][j] for i in range(m)) for j in range(m)]


def run(n, m, score_mode=False, seed_rankings=None, cheat=()):
    el = Election(n, m, score_mode=score_mode)
    t0 = time.perf_counter()
    el.setup(cheat_ballots=cheat)
    t1 = time.perf_counter()
    rng = secrets.SystemRandom()
    rankings = seed_rankings or [rng.sample(range(m), m) for _ in range(n)]
    coins = [rng.randrange(2) for _ in range(n)]
    votes = [el.cast(l, rankings[l], coins[l]) for l in range(n)]
    t2 = time.perf_counter()
    el.tally(votes)
    t3 = time.perf_counter()
    ok, msg = el.verify_universal()
    t4 = time.perf_counter()
    truth = [0] * m
    for rk in rankings:
        for i, c in enumerate(rk):
            truth[c] += el.w[i]
    res = el.decode()
    scores = res[0] if score_mode else borda_from_matrix(res, el.w)
    return {
        "el": el, "ok": ok, "msg": msg, "correct": scores == truth, "coins": coins,
        "setup": (t1 - t0) / n, "tally": (t3 - t2) / n, "verify": (t4 - t3) / n,
    }
